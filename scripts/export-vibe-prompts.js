#!/usr/bin/env node
// Writes the Vibe Coding *helper* prompts to vibe-coding-tools-101/helpers/<name>.md.
// (The six doc prompts already live in vibe-coding-tools-101/ as their long-form sources.)
// The userscript is the source: edit userscripts/vibe-coding.user.js, then run
//   node scripts/export-vibe-prompts.js
'use strict';
const fs = require('fs');
const path = require('path');
const vm = require('vm');

const root = path.join(__dirname, '..');
const src = fs.readFileSync(path.join(root, 'userscripts/vibe-coding.user.js'), 'utf8');
const outDir = path.join(root, 'vibe-coding-tools-101/helpers');

let data = null;
// No GM_* globals here, so the script takes its export branch and never touches the DOM.
vm.runInNewContext(src, { window: { __PGV_EXPORT__: d => { data = d; } }, console });
if (!data) throw new Error('vibe-coding.user.js did not call __PGV_EXPORT__');

const helpers = data.prompts.filter(p => p.cat === 'Helpers');
const slug = p => p.id.replace(/^vc-/, '');
const banner = '<!-- Generated by scripts/export-vibe-prompts.js from userscripts/vibe-coding.user.js. Edit the userscript, not this file. -->';

fs.rmSync(outDir, { recursive: true, force: true });
fs.mkdirSync(outDir, { recursive: true });
for (const p of helpers) {
  fs.writeFileSync(path.join(outDir, slug(p) + '.md'), `${banner}\n# ${p.icon} ${p.title}\n\n${p.prompt.trim()}\n`);
}
fs.writeFileSync(path.join(outDir, 'README.md'), [
  banner,
  '# Helpers',
  '',
  'Everyday coding prompts. They read `CONTEXT.md` and finish by updating `CONTEXT.md` §7 and `CHANGELOG.md`, so they work with the six doc prompts in the folder above.',
  '',
  ...helpers.map(p => `- ${p.icon} [${p.title}](./${slug(p)}.md)`),
  '',
].join('\n'));
console.log(`wrote ${helpers.length} helpers + README.md to ${path.relative(root, outDir)}/`);
