#!/usr/bin/env node
// Writes every Vibe Coding prompt to vibe-coding-tools-101/system/<name>.md, plus an index.
// The userscript is the single source: edit userscripts/vibe-coding.user.js, then run
//   node scripts/export-vibe-prompts.js
// Each file holds the exact text the palette inserts (prompt + project-memory footer).
'use strict';
const fs = require('fs');
const path = require('path');
const vm = require('vm');

const root = path.join(__dirname, '..');
const src = fs.readFileSync(path.join(root, 'userscripts/vibe-coding.user.js'), 'utf8');
const outDir = path.join(root, 'vibe-coding-tools-101/system');

let data = null;
// No GM_* globals here, so the script takes its export branch and never touches the DOM.
vm.runInNewContext(src, { window: { __PGV_EXPORT__: d => { data = d; } }, console });
if (!data) throw new Error('vibe-coding.user.js did not call __PGV_EXPORT__');

const slug = p => p.id.replace(/^v[cw]-/, '');
const fence = text => {               // a fence longer than any backtick run inside the prompt
  const longest = Math.max(2, ...(text.match(/`+/g) || []).map(s => s.length));
  return '`'.repeat(longest + 1);
};

fs.rmSync(outDir, { recursive: true, force: true });
fs.mkdirSync(outDir, { recursive: true });
const banner = '<!-- Generated by scripts/export-vibe-prompts.js from userscripts/vibe-coding.user.js. Edit the userscript, not this file. -->';

const rows = [];
let lastCat = null;
for (const p of data.prompts) {
  const text = data.fullText([p]);
  const f = fence(text);
  const next = data.prompts.find(x => x.id === p.next);
  fs.writeFileSync(path.join(outDir, slug(p) + '.md'), [
    banner,
    `# ${p.icon} ${p.title}`,
    '',
    `**Group:** ${data.groups[p.cat] || p.cat}  `,
    `**Reads:** ${p.reads.join(', ')}  `,
    `**Writes:** ${p.writes.join(', ')}  `,
    `**Next:** ${next ? `[${next.title}](./${slug(next)}.md)` : '—'}`,
    '',
    'Copy everything inside the block below (it ends with the shared project-memory footer), or insert it with the Vibe Coding userscript (`Alt+V`).',
    '',
    f + 'markdown',
    text,
    f,
    '',
  ].join('\n'));
  if (p.cat !== lastCat) { rows.push('', `## ${data.groups[p.cat] || p.cat}`, '', '| Prompt | Writes | Next |', '|---|---|---|'); lastCat = p.cat; }
  rows.push(`| ${p.icon} [${p.title}](./${slug(p)}.md) | ${p.writes.join(', ')} | ${next ? next.title : '—'} |`);
}

fs.writeFileSync(path.join(outDir, 'README.md'), [
  banner,
  '# Vibe coding prompt system',
  '',
  `${data.prompts.length} prompts, one file each, in workflow order. Every prompt owns one project file and names the next step. How the system works: [docs/vibe-coding-system.md](../../docs/vibe-coding-system.md).`,
  ...rows,
  '',
].join('\n'));
console.log(`wrote ${data.prompts.length} prompts + README.md to ${path.relative(root, outDir)}/`);
