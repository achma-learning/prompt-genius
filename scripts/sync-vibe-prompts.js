#!/usr/bin/env node
// Keeps the Vibe Coding prompts and their .md files in sync. Run after editing either side:
//   node scripts/sync-vibe-prompts.js
// 1. Doc prompts: vibe-coding-tools-101/*.md is the source → copied into userscripts/vibe-coding.user.js.
// 2. Helper prompts: the userscript is the source → written to vibe-coding-tools-101/helpers/*.md.
'use strict';
const fs = require('fs');
const path = require('path');
const vm = require('vm');

const root = path.join(__dirname, '..');
const scriptPath = path.join(root, 'userscripts/vibe-coding.user.js');
const docsDir = path.join(root, 'vibe-coding-tools-101');
const DOC_FILES = {
  'vc-context': 'generate context.md',
  'vc-changelog': 'changelogs builder.md',
  'vc-trajectory': 'generate-trajectory.md',
  'vc-readme': 'generate-readme.md',
  'vc-troubleshooting': 'generate-troubleshooting.md',
  'vc-prompts-codex': 'generate-prompts-codex.md',
};

// ── 1. .md → userscript (doc prompts) ──
let src = fs.readFileSync(scriptPath, 'utf8');
const esc = s => s.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${');
let changed = 0;
for (const [id, file] of Object.entries(DOC_FILES)) {
  const text = fs.readFileSync(path.join(docsDir, file), 'utf8').trim() + '\n';
  const at = src.indexOf(`id:'${id}'`);
  if (at < 0) throw new Error(`${id} not found in vibe-coding.user.js`);
  const start = src.indexOf('prompt:`', at) + 'prompt:`'.length;
  const end = src.slice(start).search(/(?<!\\)`\n    \},/) + start;   // closing backtick of the template literal
  const next = esc(text);
  if (src.slice(start, end) !== next) { src = src.slice(0, start) + next + src.slice(end); changed++; }
}
fs.writeFileSync(scriptPath, src);
console.log(`doc prompts: ${changed} updated from vibe-coding-tools-101/*.md`);

// ── 2. userscript → .md (helper prompts) ──
let data = null;
// No GM_* globals here, so the script takes its export branch and never touches the DOM.
vm.runInNewContext(src, { window: { __PGV_EXPORT__: d => { data = d; } }, console });
if (!data) throw new Error('vibe-coding.user.js did not call __PGV_EXPORT__');
const helpers = data.prompts.filter(p => p.cat === 'Helpers');
const outDir = path.join(docsDir, 'helpers');
const slug = p => p.id.replace(/^vc-/, '');
const banner = '<!-- Generated by scripts/sync-vibe-prompts.js from userscripts/vibe-coding.user.js. Edit the userscript, not this file. -->';
fs.rmSync(outDir, { recursive: true, force: true });
fs.mkdirSync(outDir, { recursive: true });
for (const p of helpers) fs.writeFileSync(path.join(outDir, slug(p) + '.md'), `${banner}\n# ${p.icon} ${p.title}\n\n${p.prompt.trim()}\n`);
fs.writeFileSync(path.join(outDir, 'README.md'), [
  banner, '# Helpers', '',
  'Everyday coding prompts. They read `CONTEXT.md` and finish by updating `CONTEXT.md` §7 and `CHANGELOG.md`, so they work with the six doc prompts in the folder above.',
  '', ...helpers.map(p => `- ${p.icon} [${p.title}](./${slug(p)}.md)`), '',
].join('\n'));
console.log(`helpers: wrote ${helpers.length} files + README.md to vibe-coding-tools-101/helpers/`);
